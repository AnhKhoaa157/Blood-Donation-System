CREATE INDEX idx_support_ticket_status_date ON yeucaulienhehotro (trangthai, ngaytao);
CREATE INDEX idx_support_ticket_user ON yeucaulienhehotro (nguoidungid);
CREATE INDEX idx_support_history_ticket ON lichsulienhehotro (hotroid);
